const lines = rawText.split('\n').filter(l => l.trim().length > 0);
const glossary = [];

lines.forEach(line => {
    // Match * **TERM** — definition
    const match = line.match(/\*\s+\*\*(.*?)\*\*\s*[—–-]\s*(.*)$/);
    if (match) {
        let term = match[1].trim().toUpperCase();
        let definition = match[2].trim();
        glossary.push({
            term: term,
            definition: definition
        });
    } else {
        console.warn("Could not match line:", line);
    }
});

// Sort alphabetically by term in Ukrainian collation
glossary.sort((a, b) => a.term.localeCompare(b.term, 'uk'));

fs.writeFileSync('data/vtm_glossary.json', JSON.stringify(glossary, null, 2));
