testTexts.forEach((text, i) => {
    console.log(`\nOriginal [${i}]: ${text}`);
    // Replace terms
    // We should sort rules so multi-word expressions come before single-word substrings (e.g. "Кровні пута" before "Кров")
    const sortedRules = [...rules].sort((a, b) => {
        const isMultiA = a.term.includes(' ') || a.regex.source.includes('\\s+');
        const isMultiB = b.term.includes(' ') || b.regex.source.includes('\\s+');
        if (isMultiA && !isMultiB) return -1;
        if (!isMultiA && isMultiB) return 1;
        return b.term.length - a.term.length;
    });

    let highlighted = text;
    // We can use a tokenizing/tagging approach or a combined regex
    sortedRules.forEach(rule => {
        // Find matching words surrounded by word boundaries (Cyrillic-aware)
        const pat = new RegExp(`(?<![а-яіїєґa-z0-9_])(${rule.regex.source})(?![а-яіїєґa-z0-9_])`, 'gui');
        highlighted = highlighted.replace(pat, `<mark class="vtm-term" data-term="${rule.term}">$1</mark>`);
    });
    console.log(`Highlighted [${i}]: ${highlighted}`);
});
